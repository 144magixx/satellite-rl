"""Durable human-resume gate and node-local exact-identity pause watchdog.

Integration: initialize() once per contract/node; bind rootpauseepoch into every
task. Call Gate.validate before dispatch/resume, and Gate.stop_requested at each
worker safe boundary (save the complete checkpoint before exiting). Register the
actual worker before releasing its start barrier. Launch the watchdog as a
separate persistent process, independent of controller/worker lifetime.

The receipt's root_attested_user_continue is an assertion by the integrating
root controller, not an automatic NLP determination of human authorization.
No receipt is generated by this module. This module never reboots a machine.
"""
from contextlib import contextmanager
from datetime import datetime, timezone
import argparse
import hashlib
import json
import os
from pathlib import Path
import signal
import time
import urllib.parse
import urllib.request


class GateClosed(RuntimeError):
    pass


def utc_now():
    return datetime.now(timezone.utc)


def timestamp(value):
    parsed = datetime.fromisoformat(value.replace('Z', '+00:00')) if isinstance(value, str) else value
    if parsed.tzinfo is None:
        raise ValueError('timezone-aware UTC instant required')
    return parsed.astimezone(timezone.utc)


def digest(value):
    raw = json.dumps(value, sort_keys=True, separators=(',', ':'), allow_nan=False).encode('utf8')
    return hashlib.sha256(raw).hexdigest()


def atomic_json(path, value):
    path = Path(path)
    tmp = path.with_name(path.name + '.tmp')
    with tmp.open('w', encoding='utf8') as f:
        json.dump(value, f, sort_keys=True, indent=2, allow_nan=False)
        f.flush()
        os.fsync(f.fileno())
    os.replace(tmp, path)
    if os.name == 'posix':
        fd = os.open(str(path.parent), os.O_RDONLY)
        try:
            os.fsync(fd)
        finally:
            os.close(fd)


@contextmanager
def file_lock(path, nonblocking=False):
    """OS-owned lock: death releases ownership; the persistent file is not a PID lock."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open('a+b') as f:
        if os.name == 'posix':
            import fcntl
            fcntl.flock(f, fcntl.LOCK_EX | (fcntl.LOCK_NB if nonblocking else 0))
        else:
            import msvcrt
            f.seek(0, 2)
            if not f.tell():
                f.write(b'0')
                f.flush()
            f.seek(0)
            msvcrt.locking(f.fileno(), msvcrt.LK_NBLCK if nonblocking else msvcrt.LK_LOCK, 1)
        try:
            yield
        finally:
            if os.name == 'posix':
                fcntl.flock(f, fcntl.LOCK_UN)
            else:
                f.seek(0)
                msvcrt.locking(f.fileno(), msvcrt.LK_UNLCK, 1)


def proc_identity(pid):
    """Linux exact birth/boot/argv/cwd/UID, never infer liveness from PID alone."""
    root = Path('/proc')
    p = root / str(int(pid))
    try:
        stat = (p / 'stat').read_text()
        fields = stat[stat.rfind(')') + 2:].split()
        argv = [part.decode('utf8', 'strict') for part in (p / 'cmdline').read_bytes().split(b'\0') if part]
        if fields[0] == 'Z':
            return None
        return dict(pid=int(pid), birth_ticks=int(fields[19]), state=fields[0],
                    boot_id=(root / 'sys/kernel/random/boot_id').read_text().strip(),
                    argv=argv, cwd=str(p.joinpath('cwd').resolve(strict=True)), uid=p.stat().st_uid)
    except (FileNotFoundError, ProcessLookupError):
        return None


IDENTITY_FIELDS = ('pid', 'birth_ticks', 'boot_id', 'argv', 'cwd', 'uid')


def same_identity(actual, expected):
    return actual is not None and all(actual.get(k) == expected.get(k) for k in IDENTITY_FIELDS)


def validate_scope(worker, spec):
    if worker.get('experiment_id') != spec['experiment_id']:
        raise ValueError('other experiment worker rejected')
    if any(k not in worker for k in IDENTITY_FIELDS) or type(worker['pid']) is not int or worker['pid'] <= 1:
        raise ValueError('complete exact worker identity required')
    scope = Path(spec['scope_root']).resolve()
    if not Path(worker['cwd']).resolve().is_relative_to(scope):
        raise ValueError('worker cwd outside dedicated experiment root')
    # Require a distinct absolute task/config/source path token under this root.
    if not isinstance(worker['argv'], list) or not any(str(scope) + os.sep in arg for arg in worker['argv']):
        raise ValueError('worker argv outside dedicated experiment root')
    if worker['uid'] != spec['uid']:
        raise ValueError('worker UID differs')
    parsed = urllib.parse.urlsplit(worker['stop_url'])
    if parsed.scheme != 'http' or parsed.hostname not in ('127.0.0.1', 'localhost') or parsed.username or parsed.password or parsed.query or parsed.fragment:
        raise ValueError('local explicit stop endpoint required')
    if parsed.path != '/api/runs/' + worker['task_id'] + '/stop':
        raise ValueError('stop endpoint task identity differs')


def initialize(control_dir, spec):
    """spec: experiment_id, node_id, scope_root, uid, soft_UTC, hard_UTC, contract_SHA."""
    for key in ('experiment_id', 'node_id', 'scope_root', 'uid', 'soft_UTC', 'hard_UTC', 'contract_SHA'):
        if key not in spec:
            raise ValueError('missing spec field ' + key)
    if timestamp(spec['soft_UTC']) >= timestamp(spec['hard_UTC']):
        raise ValueError('soft cutoff must precede hard deadline')
    directory = Path(control_dir)
    directory.mkdir(parents=True, exist_ok=True)
    with file_lock(directory / 'gate.lock'):
        path = directory / 'spec.json'
        if path.exists():
            if json.loads(path.read_text(encoding='utf8')) != spec:
                raise ValueError('immutable control spec differs; new contract needs separate control epoch directory')
        else:
            atomic_json(path, spec)
            atomic_json(directory / 'state.json', dict(schema='W27PauseGateV1',
                        epoch=digest(dict(spec=spec, initial=True)), hold=False, resumed_contract=False,
                        resume_receipt_ids=[], workers=[], events=[]))
    gate = Gate(directory)
    gate.refresh()
    return gate.snapshot()['epoch']


class Gate:
    def __init__(self, control_dir, clock=utc_now):
        self.directory = Path(control_dir)
        self.clock = clock
        self.spec = json.loads((self.directory / 'spec.json').read_text(encoding='utf8'))

    @contextmanager
    def transaction(self):
        with file_lock(self.directory / 'gate.lock'):
            state = json.loads((self.directory / 'state.json').read_text(encoding='utf8'))
            before = digest(state)
            yield state
            if digest(state) != before:
                atomic_json(self.directory / 'state.json', state)

    def snapshot(self):
        with file_lock(self.directory / 'gate.lock'):
            return json.loads((self.directory / 'state.json').read_text(encoding='utf8'))

    def _cutoff(self, state, now):
        if not state['resumed_contract'] and timestamp(now) >= timestamp(self.spec['soft_UTC']) and not state['hold']:
            state['hold'] = True
            state['hold_epoch'] = digest(dict(epoch=state['epoch'], contract=self.spec['contract_SHA']))
            state['hold_UTC'] = timestamp(now).isoformat()
            state['events'].append(dict(kind='durable_hold', UTC=state['hold_UTC'], reason='soft_checkpoint_deadline'))

    def refresh(self, now=None):
        with self.transaction() as state:
            self._cutoff(state, self.clock() if now is None else now)

    def validate(self, rootpauseepoch, now=None):
        # Persist cutoff first, even when an invalid caller epoch follows.
        self.refresh(now)
        state = self.snapshot()
        if state['hold'] or rootpauseepoch != state['epoch']:
            raise GateClosed('durable pause hold or stale rootpauseepoch; explicit human continuation required')
        return state['epoch']

    def stop_requested(self, rootpauseepoch, now=None):
        try:
            self.validate(rootpauseepoch, now)
            return False
        except GateClosed:
            return True

    def register_worker(self, rootpauseepoch, worker, inspector=proc_identity, *, continuation=None):
        self.refresh()
        validate_scope(worker, self.spec)
        if not same_identity(inspector(worker['pid']), worker):
            raise ValueError('worker birth/boot/argv no longer matches')
        with self.transaction() as state:
            self._cutoff(state, self.clock())
            if state['hold'] or state['epoch'] != rootpauseepoch:
                raise GateClosed('registration closed')
            for prior in state['workers']:
                if prior['task_id'] == worker['task_id'] or prior['pid'] == worker['pid']:
                    if same_identity(inspector(prior['pid']), prior):
                        raise ValueError('worker/task already has live registered owner')
                    if prior['rootpauseepoch'] == rootpauseepoch:
                        if continuation is None:
                            raise ValueError('same-epoch replacement requires independently accounted recovery; not automatic registration')
                        from .control import validate_continuation
                        r = validate_continuation(continuation['run_dir'], continuation['config'], continuation['receipt_ref'])
                        if (r['run_id'] != worker['task_id'] or r['rootpauseepoch'] != rootpauseepoch
                                or r.get('contract_SHA') != self.spec['contract_SHA']
                                or not same_identity(r.get('previous_worker'), prior)):
                            raise ValueError('planned continuation old generation/contract mismatch')
                        state['events'].append(dict(kind='planned_pilot_continuation', task_id=worker['task_id'],
                                                    receipt_SHA=digest(r), previous_worker=prior))
            state['workers'].append(dict(worker, rootpauseepoch=rootpauseepoch))

    def resume(self, receipt):
        """Only root may pass a saved explicit-user continuation receipt; never auto-call."""
        self.refresh()
        with self.transaction() as state:
            required = ('receipt_id', 'user_message_reference', 'issued_UTC', 'hold_epoch', 'contract_SHA')
            if any(not receipt.get(k) for k in required) or receipt.get('root_attested_user_continue') is not True:
                raise GateClosed('explicit human continue receipt required')
            if not state['hold'] or receipt['hold_epoch'] != state['hold_epoch'] or receipt['contract_SHA'] != self.spec['contract_SHA']:
                raise GateClosed('receipt does not bind current hold and contract')
            if timestamp(receipt['issued_UTC']) < timestamp(self.spec['hard_UTC']) or timestamp(receipt['issued_UTC']) > self.clock():
                raise GateClosed('continue must be issued after pause deadline, never in the future')
            if receipt['receipt_id'] in state['resume_receipt_ids']:
                raise GateClosed('continuation receipt cannot be replayed')
            state['resume_receipt_ids'].append(receipt['receipt_id'])
            state['epoch'] = digest(dict(previous_epoch=state['epoch'], receipt=receipt))
            state['hold'] = False
            state['resumed_contract'] = True
            state['events'].append(dict(kind='explicit_user_resume', UTC=receipt['issued_UTC'], receipt_id=receipt['receipt_id']))
            atomic_json(self.directory / ('resume_' + digest(receipt) + '.json'), receipt)
            return state['epoch']


def request_api_stop(worker):
    request = urllib.request.Request(worker['stop_url'], data=b'{}', headers={'Content-Type': 'application/json'}, method='POST')
    with urllib.request.urlopen(request, timeout=2) as response:
        return dict(status=response.status, response=response.read(1024).decode('utf8', 'replace'))


def exact_sigterm(worker):
    """pidfd closes the check-to-kill PID reuse race; no unsafe os.kill fallback."""
    if not hasattr(os, 'pidfd_open') or not hasattr(signal, 'pidfd_send_signal'):
        raise RuntimeError('pidfd signaling unavailable; fail closed and record unresolved worker')
    fd = os.pidfd_open(worker['pid'])
    try:
        if not same_identity(proc_identity(worker['pid']), worker):
            return dict(sent=False, reason='identity_changed_after_pidfd_open')
        signal.pidfd_send_signal(fd, signal.SIGTERM)
        return dict(sent=True)
    finally:
        os.close(fd)


def watchdog_tick(gate, *, now=None, inspector=proc_identity, api_stop=request_api_stop, terminate=exact_sigterm):
    """A bounded, node-local enforcement pass; no unregistered process enumeration."""
    now = gate.clock() if now is None else timestamp(now)
    gate.refresh(now)
    snapshot = gate.snapshot()
    if not snapshot['hold']:
        return dict(hold=False, unresolved=0, live=0)
    hard = now >= timestamp(gate.spec['hard_UTC'])
    actions = []
    live = unresolved = 0
    for worker in snapshot['workers']:
        validate_scope(worker, gate.spec)
        try:
            actual = inspector(worker['pid'])
            if actual is None:
                continue
            if not same_identity(actual, worker):
                # PID reused or another boot: do not API-stop or signal the replacement.
                actions.append(dict(task_id=worker['task_id'], action='identity_mismatch_no_action'))
                continue
            live += 1
            current = gate.snapshot()
            if not current['hold'] or current['epoch'] != snapshot['epoch']:
                return dict(hold=current['hold'], resumed_during_enforcement=True, live=live, unresolved=0)
            previous = snapshot.get('enforcement', {}).get(worker['task_id'], {})
            action = dict(task_id=worker['task_id'], UTC=timestamp(now).isoformat())
            if not previous.get('api_stop_attempted') or (hard and not previous.get('hard_api_stop_attempted')):
                # Recheck exact process immediately before API request as well.
                if same_identity(inspector(worker['pid']), worker):
                    try:
                        action['api_stop'] = api_stop(worker)
                    except Exception as error:
                        action['api_error'] = type(error).__name__ + ': ' + str(error)[:240]
                    action['api_stop_attempted'] = True
                    if hard:
                        action['hard_api_stop_attempted'] = True
            if hard and not previous.get('term_attempted') and same_identity(inspector(worker['pid']), worker):
                current = gate.snapshot()
                if not current['hold'] or current['epoch'] != snapshot['epoch']:
                    return dict(hold=current['hold'], resumed_during_enforcement=True, live=live, unresolved=0)
                try:
                    action['term_result'] = terminate(worker)
                except Exception as error:
                    action['term_error'] = type(error).__name__ + ': ' + str(error)[:240]
                action['term_attempted'] = True
                action['checkpoint_may_be_incomplete'] = True
                action['unknown_interaction_spend_not_zero'] = True
                action['free_replay_allowed'] = False
            if len(action) > 2:
                actions.append(action)
            if hard and same_identity(inspector(worker['pid']), worker):
                unresolved += 1
        except Exception as error:
            unresolved += 1
            actions.append(dict(task_id=worker['task_id'], UTC=timestamp(now).isoformat(), inspection_error=type(error).__name__, free_replay_allowed=False))
    if actions:
        with gate.transaction() as state:
            for action in actions:
                state.setdefault('enforcement', {}).setdefault(action['task_id'], {}).update(action)
            state['last_enforcement_UTC'] = timestamp(now).isoformat()
            state['hard_deadline_unresolved'] = unresolved
    return dict(hold=True, hard=hard, live=live, unresolved=unresolved)


def run_watchdog(control_dir, poll_seconds=1., max_seconds=86400.):
    """One guard per control directory; bounded lifetime, compact transition records."""
    if not 0.1 <= poll_seconds <= 5 or not 1 <= max_seconds <= 7 * 86400:
        raise ValueError('bounded watchdog interval/lifetime required')
    gate = Gate(control_dir)
    if max_seconds < max(1., (timestamp(gate.spec['hard_UTC']) - utc_now()).total_seconds() + 60.):
        raise ValueError('guard lifetime must cover hard deadline plus inspection margin')
    with file_lock(gate.directory / 'watchdog.lock', nonblocking=True):
        own = proc_identity(os.getpid())
        atomic_json(gate.directory / 'watchdog_owner.json', dict(identity=own, started_UTC=utc_now().isoformat(), max_seconds=max_seconds))
        start = time.monotonic()
        previous = None
        while time.monotonic() - start < max_seconds:
            try:
                outcome = watchdog_tick(gate)
            except Exception as error:
                outcome = dict(fatal=type(error).__name__, detail=str(error)[:240])
            if outcome != previous:
                atomic_json(gate.directory / 'watchdog_status.json', dict(outcome, observed_UTC=utc_now().isoformat()))
                previous = outcome
            if outcome.get('hard') and not outcome.get('live') and not outcome.get('unresolved'):
                return outcome
            time.sleep(poll_seconds)
        # Never let bounded-loop expiry become implicit resume or a false pause receipt.
        gate.refresh()
        atomic_json(gate.directory / 'watchdog_status.json', dict(stage='guard_lifetime_exhausted', hold=gate.snapshot()['hold'], last_outcome=previous, requires_operator_review=True))
        return previous


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--control-dir', required=True)
    parser.add_argument('--poll-seconds', type=float, default=1.)
    parser.add_argument('--max-seconds', type=float, default=86400.)
    args = parser.parse_args()
    run_watchdog(args.control_dir, args.poll_seconds, args.max_seconds)


if __name__ == '__main__':
    main()
